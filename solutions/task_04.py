def swap(a, b):
    # По условию: нельзя использовать третью переменную и нельзя писать a, b = b, a.
    # Используем арифметический трюк:
    # 1. a = a + b (теперь в a сумма двух чисел)
    a = a + b
    # 2. b = a - b (из суммы вычитаем старое b, получаем старое a)
    b = a - b
    # 3. a = a - b (из суммы вычитаем новое b, получаем старое b)
    a = a - b
    
    # Возвращаем кортеж из двух значений
    return a, b

if __name__ == "__main__":
    # Запрашиваем два числа
    a = int(input("Введите первое число: "))
    b = int(input("Введите второе число: "))
    # Вызываем функцию и распаковываем результат
    new_a, new_b = swap(a, b)
    print(f"Было: a={a}, b={b}")
    print(f"Стало: a={new_a}, b={new_b}")