def index_of_min(values):
    # Если список пустой, возвращаем -1
    if not values:
        return -1
    
    # Изначально предполагаем, что минимальный элемент находится на позиции 0
    min_index = 0
    
    # Проходим по списку, начиная со второго элемента (индекс 1)
    for i in range(1, len(values)):
        # Если текущий элемент меньше того, который мы считаем минимальным
        if values[i] < values[min_index]:
            # Обновляем индекс минимального элемента
            min_index = i
            
    # Возвращаем найденный индекс. 
    # Так как мы идем слева направо и используем строгое "<",
    # при равенстве элементов индекс не обновится, что гарантирует
    # возврат индекса ПЕРВОГО вхождения минимума.
    return min_index

if __name__ == "__main__":
    # Проверка работы функции на примерах из задания
    print(index_of_min([10, -3, -5, 2, 5])) # Выведет 2
    print(index_of_min([1, 2, 3]))          # Выведет 0
    print(index_of_min([4, 1, 1, 9]))       # Выведет 1
    print(index_of_min([]))                 # Выведет -1