def greet(username):
    # Возвращаем строку с приветствием, используя f-строку для подстановки имени
    return f"Hello, {username}"

if __name__ == "__main__":
    # Запрашиваем имя у пользователя
    name = input("Введите ваше имя: ")
    # Вызываем функцию и печатаем результат
    print(greet(name))